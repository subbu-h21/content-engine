// Home page: create a video without and with dropped files; the Brief opens; Claude starts /make-video in the chat.
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import { B, WS, SHOTS, call, chatText, ok, failures, fakeMessages, page, sleep, waitFor } from "./lib.mjs";

const { browser, p } = await page(9341);
const files = "D:/tmp/ce-x/_inputs";
fs.mkdirSync(files, { recursive: true });
fs.writeFileSync(`${files}/my-style-skill.md`, "---\nname: my-style\ndescription: test skill\n---\n\nUse warm colours.\n");
fs.writeFileSync(`${files}/style guide.md`, "# A style guide without front matter\n\nOnly serif type.\n");
execFileSync("ffmpeg", ["-v", "error", "-y", "-f", "lavfi", "-i", "testsrc2=size=640x360", "-frames:v", "1", `${files}/ref image.png`]);

console.log("== home");
await p.go("/");
ok("home asks the question", /What do you want to create today\?/.test(await p.text()));
ok("Create disabled while empty", await p.eval(`window.__btn("^Create$").disabled`));
await p.shot(`${SHOTS}/01_home.png`);

console.log("== create without files");
await p.eval(`window.__set(document.querySelector("form.new textarea"), "A 20 second vertical explainer on why leaves change colour in autumn. For kids.")`);
await sleep(200);
ok("Create enabled after typing", !(await p.eval(`window.__btn("^Create$").disabled`)));
await p.click("^Create$");
await sleep(4000);
const path1 = await p.path();
ok("navigated to the new video's Brief", /^\/p\/project-\d+-.+\/brief$/.test(path1), path1);
const name1 = decodeURIComponent(path1.split("/")[2]);
const dir1 = `${WS}/${name1}`;
ok("request saved", fs.existsSync(`${dir1}/brief/request.md`) && /leaves change colour/.test(fs.readFileSync(`${dir1}/brief/request.md`, "utf8")));
const title1 = JSON.parse(fs.readFileSync(`${dir1}/project.json`, "utf8")).title;
ok("working title = first sentence", title1 === "A 20 second vertical explainer on why leaves change colour in…", title1);
console.log("   folder:", name1);
await sleep(5000);
const brief1 = await p.text(".board");
ok("board shows the first stage", /Talking it through/.test(brief1), brief1.slice(0, 200));
ok("Claude's first reply in the chat (no trust question)", await waitFor(async () => /received 11 characters/.test(await chatText(p))), await chatText(p));
await p.shot(`${SHOTS}/02_brief_new_chat.png`);
const msgs = fakeMessages(dir1);
ok("Claude started with /make-video", msgs.some((m) => m.text === "/make-video"), JSON.stringify(msgs));
ok("Claude idle after its reply", (await call("GET", `/api/projects/${name1}/publish`)).body.claude === "idle");

console.log("== back to Videos, create with files");
await p.click("Videos");
await sleep(2500);
ok("back on home", (await p.path()) === "/");
ok("new video listed with stage", /A 20 second vertical explainer/.test(await p.text(".projects")), await p.text(".projects"));
await p.eval(`window.__set(document.querySelector("form.new textarea"), "How do bees make honey?")`);
const doc = await p.send("DOM.getDocument", { depth: -1 });
const { nodeId } = await p.send("DOM.querySelector", { nodeId: doc.root.nodeId, selector: "form.new input[type=file]" });
await p.send("DOM.setFileInputFiles", { nodeId, files: [`${files}/my-style-skill.md`, `${files}/style guide.md`, `${files}/ref image.png`].map((f) => f.replace(/\//g, "\\")) });
await sleep(500);
const queued = await p.text("ul.queued");
ok("three files queued with sizes", /my-style-skill\.md/.test(queued) && /style guide\.md/.test(queued) && /ref image\.png/.test(queued), queued);
await p.shot(`${SHOTS}/03_home_files.png`);
await p.click("^Create$");
await sleep(5000);
const path2 = await p.path();
const name2 = decodeURIComponent(path2.split("/")[2]);
const dir2 = `${WS}/${name2}`;
ok("second video's Brief open", /\/brief$/.test(path2), path2);
ok("skill file became a project skill", fs.existsSync(`${dir2}/.claude/skills/my-style/SKILL.md`));
ok("style guide and image are references", fs.existsSync(`${dir2}/references/style guide.md`) && fs.existsSync(`${dir2}/references/ref image.png`), fs.existsSync(`${dir2}/references`) ? fs.readdirSync(`${dir2}/references`).join(",") : "no folder");
await sleep(6000);
const brief2 = await p.text(".board");
ok("board lists the references", /ref image\.png/.test(brief2) && /style guide\.md/.test(brief2), brief2.slice(-600));
ok("board lists the skill", /Skills for this video: my-style/.test(brief2));
await p.shot(`${SHOTS}/04_brief_with_refs.png`);
console.log("   page errors:", JSON.stringify(p.errors()));
fs.writeFileSync(`${WS}/_names.json`, JSON.stringify({ leaves: name1, bees: name2 }));
browser.proc.kill();
console.log(failures() ? `${failures()} FAILED` : "all passed");
process.exit(0);
